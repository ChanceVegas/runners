#!/usr/bin/env python3
"""music_gen.py — host-side generator: compiles the chiptune songs below into
src/music_data.h (const row tables in flash). Run from the repo root:

    python3 tools/music_gen.py

Notation (one song = 8 bars of 4/4, looping):
  lead: per bar, 8 tokens = 8th notes. "E5" note, "A#5" sharp, "-" hold, "." rest.
  bass: per bar a chord root ("C", "A#", or two roots "F/G" = half bar each) and one
        shared 8-token pattern: "1" root, "8" root an octave up, "-" hold, "." rest.
  drums: per bar, 16 tokens = 16th notes: k kick, s snare, h hat, . nothing.
Row = one 16th note. Row cell codes: 0 = hold, 1 = note off, >= 2 = MIDI note
(drums: 0 none, 1 kick, 2 snare, 3 hat).
"""
import os

NOTE = {"C": 0, "C#": 1, "D": 2, "D#": 3, "E": 4, "F": 5, "F#": 6, "G": 7,
        "G#": 8, "A": 9, "A#": 10, "B": 11}

def midi(tok):
    name, octv = tok[:-1], int(tok[-1])
    return 12 * (octv + 1) + NOTE[name]

