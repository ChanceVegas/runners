def bass_root(pc):
    m = 48 + pc                      # octave 3 (C3 = 48): audible on a tiny speaker
    return m

def build(song):
    rows = []
    for bar in range(8):
        lead = song["lead"][bar].split()
        bass = song["bass"].split()
        drums = song["drums"][bar]
        roots = song["roots"][bar].split("/")
        assert len(lead) == 8 and len(bass) == 8 and len(drums) == 16, bar
        for r in range(16):
            e = r // 2
            first = (r % 2 == 0)
            lt = lead[e]
            if lt == "-" or not first: lc = 0
            elif lt == ".": lc = 1
            else: lc = midi(lt)
            root = NOTE[roots[0] if (len(roots) == 1 or e < 4) else roots[1]]
            bt = bass[e]
            if not first: bc = 0 if bt != "." else 0
            elif bt == "-": bc = 0
            elif bt == ".": bc = 1
            elif bt == "1": bc = bass_root(root)
            elif bt == "8": bc = bass_root(root) + 12
            else: raise ValueError(bt)
            # A half-bar root change re-strikes even if the pattern says hold.
            if len(roots) == 2 and e == 4 and first and bc == 0: bc = bass_root(root)
            dc = {".": 0, "k": 1, "s": 2, "h": 3}[drums[r]]
            rows.append((lc, bc, dc))
    return rows

def main():
    out = ["// music_data.h — GENERATED by tools/music_gen.py. Do not edit by hand.",
           "// Rows are 16th notes: {lead, bass, drum}. 0 = hold, 1 = off, >=2 = MIDI note;",
           "// drum 0 none, 1 kick, 2 snare, 3 hat.",
           "#pragma once", "#include <stdint.h>", ""]
    names = []
    for name, song in SONGS.items():
        rows = build(song)
        names.append((name, song, len(rows)))
        out.append(f"const uint8_t SONG_{name}[{len(rows)}][3] = {{")
        for i in range(0, len(rows), 8):
            out.append("  " + " ".join("{%d,%d,%d}," % r for r in rows[i:i + 8]))
        out.append("};")
        out.append("")
    out.append("struct SongDef { const uint8_t (*rows)[3]; uint16_t count; uint16_t bpm; uint8_t duty; };")
    out.append("// duty: lead square duty = 1/duty (2 = 50%, 4 = 25%).")
    out.append("const SongDef SONGS[] = {")
    for name, song, n in names:
        out.append(f"  {{ SONG_{name}, {n}, {song['bpm']}, {song['duty']} }},   // {name}")
    out.append("};")
    path = os.path.join(os.path.dirname(__file__), "..", "src", "music_data.h")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(path), [(n, c) for n, _, c in names])

if __name__ == "__main__":
    main()
